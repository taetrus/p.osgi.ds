package com.kk.pde2tycho.gen;

import java.util.List;
import java.util.Locale;

import com.kk.pde2tycho.model.Inventory;
import com.kk.pde2tycho.model.Launch;
import com.kk.pde2tycho.model.Project;
import com.kk.pde2tycho.model.Target;
import com.kk.pde2tycho.model.TargetJar;

/** MIGRATION-REPORT.md: what was converted, resolved, vendored and changed, and what was not migrated. */
final class ReportGenerator {

	private ReportGenerator() {
	}

	static String report(Inventory inv, Launch launch, List<String> notes) {
		Target target = inv.target();
		String targetId = PomGenerator.targetId(inv);
		StringBuilder sb = new StringBuilder("# Migration report\n\n");
		sb.append("Generated by pde2tycho from `").append(inv.workspace()).append("`.\n\n");
		sb.append("Build: `mvn clean verify` (JDK 17+). Run: `distribution/scripts/run.sh` (macOS)")
				.append(" or `distribution\\scripts\\run.bat` (Windows).\n\n");
		sb.append("## Modules\n\n");
		for (Project p : inv.modules()) {
			sb.append("- `").append(p.name()).append("` — ").append(p.kind().name().toLowerCase(Locale.ROOT))
					.append(" `").append(p.bsn()).append("` ").append(p.version()).append('\n');
		}
		sb.append("\n## Target platform (`").append(targetId).append("`)\n\n");
		sb.append("- ").append(target.locations().size()).append(" Maven/p2 location(s) copied verbatim\n");
		sb.append("- ").append(target.resolved().size()).append(" directory jar(s) found on Maven Central\n");
		sb.append("- ").append(target.vendor().size()).append(" jar(s) vendored into `").append(targetId)
				.append("/vendor/plugins/` — commit them; the root .gitignore does not exclude them\n");
		for (TargetJar jar : target.vendor()) {
			sb.append("  - `").append(jar.bsn()).append("` ").append(jar.version()).append(": ").append(jar.reason())
					.append('\n');
		}
		sb.append("\n## Product\n\n");
		sb.append("- Launch `").append(launch.name()).append("` → `distribution/").append(launch.productId())
				.append(".product` with ").append(launch.bundles().size()).append(" bundle(s)\n");
		sb.append("- Files the product needs under `configuration/` (e.g. logback.xml) go in")
				.append(" `distribution/configuration/`\n");
		sb.append("\n## Changes to arguments and files\n\n");
		appendList(sb, notes);
		sb.append("\n## Scan warnings\n\n");
		appendList(sb, inv.warnings());
		sb.append("\n## Not migrated\n\n");
		sb.append("- Tests: test folders were copied but are not compiled (see the `default-testCompile` override in")
				.append(" the parent pom). To migrate them, follow docs/adding-tests-to-a-tycho-project.md in the")
				.append(" pde2tycho source repository.\n");
		sb.append("- Other launch configurations: only `").append(launch.name()).append("` became a product.\n");
		return sb.toString();
	}

	private static void appendList(StringBuilder sb, List<String> items) {
		if (items.isEmpty()) {
			sb.append("- none\n");
		}
		for (String item : items) {
			sb.append("- ").append(item).append('\n');
		}
	}
}
